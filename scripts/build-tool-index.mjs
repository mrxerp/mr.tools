/**
 * build-tool-index.mjs
 *
 * Scans src/tools/<family>/<tool>/ for every tool folder and generates
 * src/data/generated/index.ts, the single source of truth for the home page,
 * family hubs, tool routes, search, sitemap, and related-tool linking.
 *
 * Tool contract:
 *   - src/tools/<family>/_meta.ts  exports `meta` (FamilyMeta)
 *   - src/tools/<family>/<slug>/meta.ts  exports `meta` (ToolMeta)
 *
 * Fail-closed: missing or malformed meta stops the build.
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const toolsRoot = join(root, "src", "tools");
const outDir = join(root, "src", "data", "generated");
const outFile = join(outDir, "index.ts");

const REQUIRED_TOOL = [
  "slug",
  "name",
  "tagline",
  "description",
  "tags",
  "icon",
  "difficulty",
  "offline",
  "related",
];
const REQUIRED_FAMILY = ["id", "name", "tagline", "description", "icon"];

function fail(where, msg) {
  throw new Error(`[build-tool-index] ${where}: ${msg}`);
}

function check(obj, required, where, kind = "tool") {
  for (const k of required) {
    const v = obj[k];
    if (v === undefined || v === null || v === "") {
      fail(where, `missing required field "${k}"`);
    }
  }
  if (kind !== "family") {
    if (!Array.isArray(obj.tags) || !obj.tags.every((t) => typeof t === "string")) {
      fail(where, `"tags" must be a string array`);
    }
    if (!["Easy", "Medium", "Hard"].includes(obj.difficulty)) {
      fail(where, `"difficulty" must be Easy | Medium | Hard`);
    }
    if (typeof obj.offline !== "boolean") {
      fail(where, `"offline" must be a boolean`);
    }
    if (!Array.isArray(obj.related)) {
      fail(where, `"related" must be an array`);
    }
  }
}

async function loadMeta(filePath, where) {
  if (!existsSync(filePath)) fail(where, `missing ${filePath}`);
  const mod = await import(pathToFileURL(filePath).href);
  const meta = mod?.meta;
  if (!meta || typeof meta !== "object") {
    fail(where, `${filePath} must export a "meta" object`);
  }
  return meta;
}

function tsQuote(v) {
  return JSON.stringify(v);
}

async function main() {
  if (!existsSync(toolsRoot)) {
    fail("setup", `no tools directory at ${toolsRoot}`);
  }

  const families = [];
  const familyDirs = readdirSync(toolsRoot)
    .filter((d) => statSync(join(toolsRoot, d)).isDirectory())
    .sort();

  for (const familyId of familyDirs) {
    const familyDir = join(toolsRoot, familyId);
    if (familyId.startsWith("_")) continue;
    const familyMeta = await loadMeta(
      join(familyDir, "_meta.ts"),
      `family "${familyId}"`,
    );
    check(familyMeta, REQUIRED_FAMILY, `family "${familyId}"`, "family");
    if (familyMeta.id !== familyId) {
      fail(`family "${familyId}"`, `meta.id "${familyMeta.id}" must equal folder name`);
    }

    const toolDirs = readdirSync(familyDir)
      .filter((d) => statSync(join(familyDir, d)).isDirectory())
      .sort();

    for (const slug of toolDirs) {
      if (slug.startsWith("_")) continue;
      const where = `tool "${familyId}/${slug}"`;
      const toolMeta = await loadMeta(join(familyDir, slug, "meta.ts"), where);
      check(toolMeta, REQUIRED_TOOL, where);
      if (toolMeta.slug !== slug) {
        fail(where, `meta.slug "${toolMeta.slug}" must equal folder name`);
      }
      if (!existsSync(join(familyDir, slug, "index.astro"))) {
        fail(where, `missing index.astro`);
      }
      families.push({ family: familyMeta, tool: toolMeta });
    }
  }

  families.sort((a, b) =>
    a.family.name.toLowerCase().localeCompare(b.family.name.toLowerCase()),
  );

  const seenFamilies = new Map();
  const familyRows = [];
  for (const { family } of families) {
    if (!seenFamilies.has(family.id)) {
      seenFamilies.set(family.id, familyRows.length);
      familyRows.push(family);
    }
  }

  const toolRows = families.map(({ family, tool }) => ({
    ...tool,
    href: `/tools/${family.id}/${tool.slug}/`,
    familyName: family.name,
    familyHref: `/tools/${family.id}/`,
  }));

  const searchIndex = toolRows.map((t) => ({
    slug: t.slug,
    name: t.name,
    family: t.familyName,
    familyId: t.href.split("/")[2],
    tags: t.tags,
    tagline: t.tagline,
    href: t.href,
  }));

  const dupes = new Set();
  for (const t of toolRows) {
    const key = `${t.familyHref}${t.slug}`;
    if (dupes.has(key)) fail("index", `duplicate slug ${t.slug} in ${t.familyHref}`);
    dupes.add(key);
  }

  mkdirSync(outDir, { recursive: true });

  const code = `// AUTO-GENERATED by scripts/build-tool-index.mjs - do not edit.
import type { FamilyMeta, ToolRecord } from "@/types/tool";

export const families: FamilyMeta[] = ${tsQuote(familyRows)};

export const tools: ToolRecord[] = ${tsQuote(toolRows)};

export interface SearchHit {
  slug: string;
  name: string;
  family: string;
  familyId: string;
  tags: string[];
  tagline: string;
  href: string;
}

export const searchIndex: SearchHit[] = ${tsQuote(searchIndex)};

export function findTool(slug: string, family: string): ToolRecord | undefined {
  return tools.find((t) => t.slug === slug && t.href.includes(\`/tools/\${family}/\`));
}

export function relatedFor(tool: ToolRecord, n = 3): ToolRecord[] {
  const picks: ToolRecord[] = [];
  const seen = new Set<string>([tool.href]);
  for (const r of tool.related) {
    const hit = tools.find((t) => t.slug === r);
    if (hit && !seen.has(hit.href)) {
      picks.push(hit);
      seen.add(hit.href);
      if (picks.length >= n) return picks;
    }
  }
  for (const t of tools) {
    if (seen.has(t.href)) continue;
    if (t.familyHref === tool.familyHref) {
      picks.push(t);
      seen.add(t.href);
      if (picks.length >= n) return picks;
    }
  }
  for (const t of tools) {
    if (seen.has(t.href)) continue;
    picks.push(t);
    seen.add(t.href);
    if (picks.length >= n) return picks;
  }
  return picks;
}
`;

  writeFileSync(outFile, code);
  const nTools = toolRows.length;
  const nFamilies = familyRows.length;
  console.log(`[build-tool-index] generated index.ts - ${nFamilies} families, ${nTools} tools`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
