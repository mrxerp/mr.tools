const SHORTCODE_TO_UNICODE: Record<string, string> = EMOJI_DATA;
const UNICODE_TO_SHORTCODE: Record<string, string> = Object.fromEntries(
  Object.entries(EMOJI_DATA).map(([k, v]) => [v, k]),
);

export function shortcodeToUnicode(text: string): string {
  return text.replace(/:([a-z0-9_+-]+):/gi, (match, name) => {
    const lower = name.toLowerCase();
    return SHORTCODE_TO_UNICODE[lower] || match;
  });
}

export function unicodeToShortcode(text: string): string {
  let result = text;
  for (const [emoji, shortcode] of Object.entries(UNICODE_TO_SHORTCODE)) {
    const regex = new RegExp(emoji.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "g");
    result = result.replace(regex, `:${shortcode}:`);
  }
  return result;
}

export function searchEmoji(query: string): Array<{ shortcode: string; unicode: string }> {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  const results: Array<{ shortcode: string; unicode: string }> = [];
  for (const [shortcode, unicode] of Object.entries(SHORTCODE_TO_UNICODE)) {
    if (shortcode.includes(q)) {
      results.push({ shortcode, unicode });
      if (results.length >= 50) break;
    }
  }
  return results;
}

export function getAllEmoji(): Array<{ shortcode: string; unicode: string }> {
  return Object.entries(SHORTCODE_TO_UNICODE).map(([shortcode, unicode]) => ({ shortcode, unicode }));
}